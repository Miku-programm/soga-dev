			var result []reflect.Value
			panicked := false
			func() {
				defer func() {
					if recover() != nil {
						panicked = true
					}
				}()
				method := reflect.ValueOf(b).MethodByName(tc.method)
				args := make([]reflect.Value, len(tc.args))
				for j, arg := range tc.args {
					args[j] = reflect.ValueOf(arg).Convert(method.Type().In(j))
				}
				result = method.Call(args)
			}()
