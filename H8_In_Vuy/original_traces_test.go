func TestHashGoldenVectors(t *testing.T) {
	for _, tc := range []struct {
		name string
		got  []byte
		want string
	}{
		{"MD5", RP_qK7a([]byte("abc")), "900150983cd24fb0d6963f7d28e17f72"},
		{"SHA1", YhCPGpz([]byte("abc")), "a9993e364706816aba3e25717850c26c9cd0d89d"},
		{"HMAC-MD5", YPrsw38MN([]byte("key"), []byte("The quick brown fox jumps over the lazy dog")), "80070713463e7749b90c2dc24911e275"},
		{"HMAC-SHA1", B4_4_BnW([]byte("key"), []byte("The quick brown fox jumps over the lazy dog")), "de7c9b85b8b78aa6bc8a7a36f70a90701c9db4d9"},
	} {
		if hex.EncodeToString(tc.got) != tc.want {
			t.Fatalf("%s: %x", tc.name, tc.got)
		}
	}
}
