// IsPaddingValid 原入口 0x126df60，保留 int32 截断及上下界加减溢出。
func (c *R0J19auWof) IsPaddingValid(value string, from, to int32, method AdpPM6) bool {
	if len(value) == 0 {
		return false
	}
	if to <= 0 {
		r := c.GetNormalizedXPaddingBytes()
		from, to = r.AS9zG362, r.HHTPwX0N
	}
	if method == "tokenish" {
		var bits uint64
		for i := 0; i < len(value); i++ {
			bits += uint64(paddingBitsAt3790D20[value[i]])
		}
		size := int32((bits + 7) >> 3)
		return size >= max(int32(0), from-2) && size <= to+2
	}
	size := int32(len(value))
	return size >= from && size <= to
}
